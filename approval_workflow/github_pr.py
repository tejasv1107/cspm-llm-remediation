"""Deliver a remediation as a GitHub pull request (PyGithub, GitHub App auth)."""

from __future__ import annotations

import hashlib
import logging
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from github import Auth, Github, GithubException, UnknownObjectException

from classifier.predict import Prediction
from ingestion.schema import FindingRecord
from rag_pipeline.prompt_builder import PromptBundle
from rag_pipeline.validator import ValidationResult, summarise

logger = logging.getLogger(__name__)

PR_LABEL = "cspm-remediation"


@dataclass
class PullRequestResult:
    """What happened when we tried to open a PR for a finding."""

    number: int
    url: str
    branch: str
    path: str
    created: bool  # False => an open PR for this finding already existed (duplicate suppressed)


def _slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-") or "unknown"


def _finding_hash(finding: FindingRecord) -> str:
    return hashlib.sha1(finding.finding_id.encode("utf-8")).hexdigest()[:12]


def branch_name(finding: FindingRecord) -> str:
    """Deterministic per (client, finding) - this is what makes duplicate detection possible."""
    return f"cspm/{_slug(finding.client_id)}/{_finding_hash(finding)}"


def file_path(finding: FindingRecord) -> str:
    """Repository path, namespaced by client so tenants never share a file."""
    return f"remediations/{_slug(finding.client_id)}/{_slug(finding.control_id or 'finding')}/{_finding_hash(finding)}.tf"


def render_pr_body(
    finding: FindingRecord,
    prediction: Prediction | None,
    validation: ValidationResult | None,
    bundle: PromptBundle | None,
) -> str:
    """Full-context PR description: finding, urgency + SHAP, sources, validation, checklist."""
    lines = [
        f"## Automated remediation for `{finding.control_id or finding.title}`",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Finding ID | `{finding.finding_id}` |",
        f"| Title | {finding.title} |",
        f"| Severity | {finding.severity.value} |",
        f"| Resource | `{finding.resource_arn}` ({finding.resource_type}) |",
        f"| Region | {finding.region} |",
        f"| Account tier | {finding.account_tier.value} |",
        f"| Internet exposed | {'yes' if finding.is_internet_exposed else 'no'} |",
        f"| Client | `{finding.client_id}` |",
    ]
    if prediction:
        lines += ["", f"### Urgency: **{prediction.label.value}** (source: {prediction.source})"]
        if prediction.top_features:
            lines.append("Top SHAP drivers: " + ", ".join(f"`{f}` ({v:+.2f})" for f, v in prediction.top_features))
    if bundle and bundle.module_names:
        lines += ["", "### Reference modules used", *[f"- `{m}`" for m in bundle.module_names]]
    if validation:
        lines += ["", "### Automated validation", "```", summarise(validation), "```"]
    lines += [
        "",
        "### Reviewer checklist",
        "- [ ] The change only tightens configuration; nothing is deleted or recreated",
        "- [ ] Values (resource IDs, CIDRs, regions) match the finding",
        "- [ ] `terraform plan` output reviewed",
        "",
        "_Generated by cspm-llm-remediation. A human must approve before merge._",
    ]
    return "\n".join(lines)


class GitHubPRClient:
    """Creates branches, commits Terraform files and opens PRs in one target repository."""

    def __init__(self, repo_full_name: str | None = None, base_branch: str | None = None, github: Github | None = None) -> None:
        self.repo_full_name = repo_full_name or os.environ["GITHUB_REPO"]
        self.base_branch = base_branch or os.getenv("GITHUB_BASE_BRANCH", "main")
        self.github = github or self._github_from_env()
        self.repo = self.github.get_repo(self.repo_full_name)

    @staticmethod
    def _github_from_env() -> Github:
        """Authenticate from the environment: a personal access token if set, else a GitHub App.

        A PAT (``GITHUB_TOKEN``) is the simplest path for a single-repo demo/dev setup;
        a GitHub App installation is preferred for a real multi-repo MSP deployment
        (per-repo installs, no long-lived user token). Both produce the same ``Github``
        client surface used by the rest of this module.
        """
        token = os.getenv("GITHUB_TOKEN")
        if token:
            return Github(auth=Auth.Token(token))
        private_key = Path(os.environ["GITHUB_PRIVATE_KEY_PATH"]).read_text(encoding="utf-8")
        app_auth = Auth.AppAuth(int(os.environ["GITHUB_APP_ID"]), private_key)
        return Github(auth=app_auth.get_installation_auth(int(os.environ["GITHUB_INSTALLATION_ID"])))

    # ------------------------------------------------------------------ duplicates
    def find_existing_pr(self, finding: FindingRecord) -> Any | None:
        """Open PR whose head is this finding's deterministic branch, if any."""
        owner = self.repo_full_name.split("/")[0]
        pulls = list(self.repo.get_pulls(state="open", head=f"{owner}:{branch_name(finding)}"))
        return pulls[0] if pulls else None

    # ---------------------------------------------------------------------- create
    def create_remediation_pr(
        self,
        finding: FindingRecord,
        hcl: str,
        prediction: Prediction | None = None,
        validation: ValidationResult | None = None,
        bundle: PromptBundle | None = None,
    ) -> PullRequestResult:
        """Open a PR containing ``hcl``; if one is already open for this finding, return it instead."""
        branch, path = branch_name(finding), file_path(finding)

        existing = self.find_existing_pr(finding)
        if existing is not None:
            logger.info("Duplicate finding %s: PR #%s already open", finding.finding_id, existing.number)
            return PullRequestResult(existing.number, existing.html_url, branch, path, created=False)

        base_sha = self.repo.get_branch(self.base_branch).commit.sha
        try:
            self.repo.create_git_ref(ref=f"refs/heads/{branch}", sha=base_sha)
        except GithubException as exc:
            if exc.status != 422:  # 422 = branch already exists (e.g. earlier run died before the PR)
                raise

        message = f"fix({finding.control_id or 'cspm'}): remediate {finding.resource_type} finding"
        try:
            current = self.repo.get_contents(path, ref=branch)
            self.repo.update_file(path, message, hcl, current.sha, branch=branch)
        except UnknownObjectException:
            self.repo.create_file(path, message, hcl, branch=branch)

        urgency = prediction.label.value if prediction else "UNRATED"
        pr = self.repo.create_pull(
            title=f"[CSPM] {finding.control_id or 'finding'}: {finding.title} ({urgency})",
            body=render_pr_body(finding, prediction, validation, bundle),
            head=branch,
            base=self.base_branch,
        )
        try:
            pr.add_to_labels(PR_LABEL, f"urgency:{urgency.lower()}")
        except GithubException:
            logger.warning("Could not label PR #%s", pr.number, exc_info=True)
        return PullRequestResult(pr.number, pr.html_url, branch, path, created=True)
